  DateTime? expiresAt;

  /// When the invoice was paid (null if not paid)
  DateTime? paidAt;

  /// Transaction ID of payment (null if not paid)
  String? paymentTxid;

  /// Amount received in satoshis (stored as string to handle BigInt)
  String? amountReceived;

  /// Invoice metadata (serialized as JSON)
  String? metadataJson;

  /// Structured output specifications (serialized as JSON)
  /// Contains P2PKH and P2MS output specs for multi-output invoices
  String? outputsJson;

  InvoiceEntity();

  /// Create from the invoice read model the projection stores.
  factory InvoiceEntity.fromDomain(InvoiceReadModel invoice) {
    final outputs = invoice.outputs;
    return InvoiceEntity()
      ..invoiceId = invoice.invoiceId
      ..walletId = invoice.walletId
      ..addressesJson = _encodeList(invoice.addresses)
      ..amount = invoice.amount.toString()
      ..description = invoice.description
      ..status = invoice.status.name
      ..createdAt = invoice.createdAt
      ..expiresAt = invoice.expiresAt
      ..paidAt = invoice.paidAt
      ..paymentTxid = invoice.paymentTxid
      ..amountReceived = invoice.amountReceived?.toString()
      ..metadataJson = _encodeJson(invoice.metadata)
      ..outputsJson = outputs == null
          ? null
          : jsonEncode(outputs.map((o) => o.toMap()).toList());
  }

  /// Convert to the invoice read model (audit S-07: previously a Map).
  InvoiceReadModel toDomain() {
    final rawOutputs = outputsJson;
    return InvoiceReadModel(
      invoiceId: invoiceId,
      walletId: walletId,
      addresses: _decodeList(addressesJson),
      amount: BigInt.parse(amount),
      outputs: rawOutputs == null
          ? null
          : (jsonDecode(rawOutputs) as List)
              .map((o) => InvoiceOutputSpec.fromMap(
                  Map<String, dynamic>.from(o as Map)))
              .toList(),
      description: description,
      status: InvoiceStatus.values.firstWhere(
        (s) => s.name == status,
        orElse: () => InvoiceStatus.pending,
      ),
      createdAt: createdAt,
      expiresAt: expiresAt,
      paidAt: paidAt,
      paymentTxid: paymentTxid,
      amountReceived:
          amountReceived != null ? BigInt.parse(amountReceived!) : null,
      lastUpdated: paidAt ?? createdAt,
      metadata: metadataJson != null
          ? _decodeJson(metadataJson!)
          : <String, dynamic>{},
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'invoiceId': invoiceId,
      'walletId': walletId,
      'addressesJson': addressesJson,
      'amount': amount,
      'description': description,
      'status': status,
      'createdAt': createdAt.toIso8601String(),
      'expiresAt': expiresAt?.toIso8601String(),
      'paidAt': paidAt?.toIso8601String(),
      'paymentTxid': paymentTxid,
      'amountReceived': amountReceived,
      'metadataJson': metadataJson,
      'outputsJson': outputsJson,
    };
  }

  /// Deserialize from JSON for restore
  factory InvoiceEntity.fromJson(Map<String, dynamic> json) {
    return InvoiceEntity()
      ..invoiceId = json['invoiceId'] as String
      ..walletId = json['walletId'] as String
      ..addressesJson = json['addressesJson'] as String
      ..amount = json['amount'] as String
      ..description = json['description'] as String?
      ..status = json['status'] as String
      ..createdAt = DateTime.parse(json['createdAt'] as String)
      ..expiresAt = json['expiresAt'] != null ? DateTime.parse(json['expiresAt'] as String) : null
      ..paidAt = json['paidAt'] != null ? DateTime.parse(json['paidAt'] as String) : null
      ..paymentTxid = json['paymentTxid'] as String?
      ..amountReceived = json['amountReceived'] as String?
      ..metadataJson = json['metadataJson'] as String?
      ..outputsJson = json['outputsJson'] as String?;
  }
