/// LibSpiffy's Isar schemas that developers can add to their Isar instance.
/// 
/// Usage:
/// ```dart
/// // After running: dart run build_runner build
/// final isar = await Isar.open([
///   ...LibSpiffySchemas.allSchemas,  // LibSpiffy + Eventador schemas
///   UserSchema,                      // Developer's own schemas
///   OrderSchema,
///   ProductSchema,
/// ]);
/// 
/// final walletStorage = IsarWalletStorage(isar);
/// ```
class LibSpiffySchemas {
  /// All wallet-related schemas for LibSpiffy (read models only)
  /// Note: These schemas are generated by Isar after running build_runner
  static List<CollectionSchema<dynamic>> get walletSchemas {
    // Generated schemas from build_runner
    return [
      BlockHeaderEntitySchema,
      MerkleProofEntitySchema,
      BitcoinUtxoEntitySchema,
      BitcoinTransactionEntitySchema,
      WalletMetadataEntitySchema,
      AddressEntitySchema,
      TransactionAddressEntitySchema,
      InvoiceEntitySchema,
      PaymentChannelEntitySchema,
    ];
  }
  
  /// All required schemas including event store and projections
  /// Use this when initializing LibSpiffy with full event sourcing support
  static List<CollectionSchema<dynamic>> get allSchemas {
    return [
      ...walletSchemas,
      ...IsarEventStore.allSchemas,
    ];
  }
}

/// Block header storage entity for SPV validation
@collection
class BlockHeaderEntity {
  Id id = Isar.autoIncrement;

  /// Block height
  @Index()
  late int height;

  /// Block hash (hex string)
  @Index(unique: true)
  late String hash;

  /// Previous block hash
  late String prevBlockHash;

  /// Merkle root hash
  late String merkleRoot;

  /// Block timestamp (Unix timestamp)
  late int timestamp;

  /// Block version
  late int version;

  /// Difficulty bits
  late int bits;

  /// Block nonce
  late int nonce;

  /// Whether this header is orphaned due to reorganization
  @Index()
  late bool isOrphaned;

  /// When this header was stored
  late DateTime storedAt;

  BlockHeaderEntity();

  /// Create from SpiffyNode BlockHeader
  factory BlockHeaderEntity.fromBlockHeader(BlockHeader blockHeader, int height) {
    return BlockHeaderEntity()
      ..height = height
      ..hash = blockHeader.blockHash().toString()
      ..prevBlockHash = blockHeader.prevBlock.toString()
      ..merkleRoot = blockHeader.merkleRoot.toString()
      ..timestamp = blockHeader.timestamp.millisecondsSinceEpoch ~/ 1000
      ..version = blockHeader.version
      ..bits = blockHeader.bits
      ..nonce = blockHeader.nonce
      ..isOrphaned = false
      ..storedAt = DateTime.now();
  }

  /// Convert back to SpiffyNode BlockHeader
  /// Note: This reconstructs the BlockHeader from stored values
  BlockHeader toBlockHeader() {
    return BlockHeader(
      version: version,
      prevBlock: Hash.fromHex(prevBlockHash),
      merkleRoot: Hash.fromHex(merkleRoot),
      timestamp: DateTime.fromMillisecondsSinceEpoch(timestamp * 1000),
      bits: bits,
      nonce: nonce,
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'height': height,
      'hash': hash,
      'prevBlockHash': prevBlockHash,
      'merkleRoot': merkleRoot,
      'timestamp': timestamp,
      'version': version,
      'bits': bits,
      'nonce': nonce,
      'isOrphaned': isOrphaned,
      'storedAt': storedAt.toIso8601String(),
    };
  }

  /// Deserialize from JSON for restore
  factory BlockHeaderEntity.fromJson(Map<String, dynamic> json) {
    return BlockHeaderEntity()
      ..height = json['height'] as int
      ..hash = json['hash'] as String
      ..prevBlockHash = json['prevBlockHash'] as String
      ..merkleRoot = json['merkleRoot'] as String
      ..timestamp = json['timestamp'] as int
      ..version = json['version'] as int
      ..bits = json['bits'] as int
      ..nonce = json['nonce'] as int
      ..isOrphaned = json['isOrphaned'] as bool
      ..storedAt = DateTime.parse(json['storedAt'] as String);
  }
}

