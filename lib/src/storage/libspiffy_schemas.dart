/// LibSpiffy's Isar schemas that developers can add to their Isar instance.
/// 
/// Usage:
/// ```dart
/// // After running: dart run build_runner build
/// final isar = await Isar.open([
///   ...LibSpiffySchemas.allSchemas,  // LibSpiffy + Eventador schemas
///   UserSchema,                      // Developer's own schemas
///   OrderSchema,
///   ProductSchema,
/// ]);
/// 
/// final walletStorage = IsarWalletStorage(isar);
/// ```
class LibSpiffySchemas {
  /// All wallet-related schemas for LibSpiffy (read models only)
  /// Note: These schemas are generated by Isar after running build_runner
  static List<CollectionSchema<dynamic>> get walletSchemas {
    // Generated schemas from build_runner
    return [
      BlockHeaderEntitySchema,
      MerkleProofEntitySchema,
      AncestorTransactionEntitySchema,
      PendingReceiveEntitySchema,
      DeferredPaymentEntitySchema,
      BitcoinUtxoEntitySchema,
      BitcoinTransactionEntitySchema,
      WalletMetadataEntitySchema,
      AddressEntitySchema,
      TransactionAddressEntitySchema,
      InvoiceEntitySchema,
      PaymentChannelEntitySchema,
    ];
  }
  
  /// All required schemas including event store and projections
  /// Use this when initializing LibSpiffy with full event sourcing support
  static List<CollectionSchema<dynamic>> get allSchemas {
    return [
      ...walletSchemas,
      ...IsarEventStore.allSchemas,
      ...IsarStorage.requiredSchemas,
    ];
  }
}

/// Block header storage entity for SPV validation
@collection
class BlockHeaderEntity {
  Id id = Isar.autoIncrement;

  /// Block height
  @Index()
  late int height;

  /// Block hash (hex string)
  @Index(unique: true)
  late String hash;

  /// Previous block hash
  late String prevBlockHash;

  /// Merkle root hash
  late String merkleRoot;

  /// Block timestamp (Unix timestamp)
  late int timestamp;

  /// Block version
  late int version;

  /// Difficulty bits
  late int bits;

  /// Block nonce
  late int nonce;

  /// Whether this header is orphaned due to reorganization
  @Index()
  late bool isOrphaned;

  /// When this header was stored
  late DateTime storedAt;

  BlockHeaderEntity();

  /// Create from SpiffyNode BlockHeader
  factory BlockHeaderEntity.fromBlockHeader(BlockHeader blockHeader, int height) {
    return BlockHeaderEntity()
      ..height = height
      ..hash = blockHeader.blockHash().toString()
      ..prevBlockHash = blockHeader.prevBlock.toString()
      ..merkleRoot = blockHeader.merkleRoot.toString()
      ..timestamp = blockHeader.timestamp.millisecondsSinceEpoch ~/ 1000
      ..version = blockHeader.version
      ..bits = blockHeader.bits
      ..nonce = blockHeader.nonce
      ..isOrphaned = false
      ..storedAt = DateTime.now();
  }

  /// Convert back to SpiffyNode BlockHeader
  /// Note: This reconstructs the BlockHeader from stored values
  BlockHeader toBlockHeader() {
    return BlockHeader(
      version: version,
      prevBlock: Hash.fromHex(prevBlockHash),
      merkleRoot: Hash.fromHex(merkleRoot),
      timestamp: DateTime.fromMillisecondsSinceEpoch(timestamp * 1000),
      bits: bits,
      nonce: nonce,
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'height': height,
      'hash': hash,
      'prevBlockHash': prevBlockHash,
      'merkleRoot': merkleRoot,
      'timestamp': timestamp,
      'version': version,
      'bits': bits,
      'nonce': nonce,
      'isOrphaned': isOrphaned,
      'storedAt': storedAt.toIso8601String(),
    };
  }

  /// Deserialize from JSON for restore
  factory BlockHeaderEntity.fromJson(Map<String, dynamic> json) {
    return BlockHeaderEntity()
      ..height = json['height'] as int
      ..hash = json['hash'] as String
      ..prevBlockHash = json['prevBlockHash'] as String
      ..merkleRoot = json['merkleRoot'] as String
      ..timestamp = json['timestamp'] as int
      ..version = json['version'] as int
      ..bits = json['bits'] as int
      ..nonce = json['nonce'] as int
      ..isOrphaned = json['isOrphaned'] as bool
      ..storedAt = DateTime.parse(json['storedAt'] as String);
  }
}

/// Merkle proof storage entity for SPV validation
@collection
class MerkleProofEntity {
  Id id = Isar.autoIncrement;

  /// Transaction ID this proof is for
  ///
  /// Rows are never deleted (bead mny): one row per (txid, block hash), and
  /// at most one current (verified or pendingHeader) row per txid. Both are enforced by
  /// [IsarWalletStorage.storeMerkleProof] rather than unique indexes: stores
  /// written before audit S-13 hold duplicates, and Isar refuses to open a
  /// collection whose new unique index the existing rows violate.
  @Index()
  late String txid;

  /// Block hash containing this transaction; null while its header is not
  /// known. Rows written before bead mny hold the placeholder 'pending'
  /// instead (read as null).
  @Index()
  String? blockHash;

  /// [MerkleProofStatus] name. Null on rows written before bead mny, which
  /// read as `pendingHeader` when [blockHash] is 'pending' and as `verified`
  /// otherwise.
  ///
  /// The composite (status, blockHeight) index serves the status queries
  /// (prefix) and the proofs of one status at the heights a reorganization
  /// changed, without reading every orphaned or rejected proof (bead
  /// libspiffy-hg0).
  @Index(composite: [CompositeIndex('blockHeight')])
  String? status;

  /// When [status] last changed.
  DateTime? statusChangedAt;

  /// Block height
  late int blockHeight;

  /// Position of transaction in block
  late int position;

  /// Merkle proof hashes (serialized as JSON)
  late String merkleProofJson;

  /// When this proof was stored
  late DateTime createdAt;

  MerkleProofEntity();

  /// Create from MerkleProof
  factory MerkleProofEntity.fromMerkleProof(MerkleProof proof) {
    return MerkleProofEntity()..setFrom(proof);
  }

  /// Overwrite every column but [id] with [proof].
  void setFrom(MerkleProof proof) {
    txid = proof.txid;
    blockHash = proof.blockHash == MerkleProof.legacyPendingBlockHash ? null : proof.blockHash;
    blockHeight = proof.blockHeight;
    position = proof.position;
    merkleProofJson = proof.merkleProof.join(',');
    createdAt = proof.createdAt;
    status = proof.status.name;
    statusChangedAt = proof.statusChangedAt;
  }

  /// Convert back to MerkleProof
  MerkleProof toMerkleProof() {
    final legacyPending = blockHash == MerkleProof.legacyPendingBlockHash;
    final stored = status;
    return MerkleProof(
      blockHash: legacyPending ? null : blockHash,
      txid: txid,
      // ''.split(',') is [''] — drop empty segments (audit S-13).
      merkleProof: merkleProofJson.split(',').where((s) => s.isNotEmpty).toList(),
      position: position,
      blockHeight: blockHeight,
      createdAt: createdAt,
      status: stored != null
          ? MerkleProofStatus.values.byName(stored)
          : (legacyPending ? MerkleProofStatus.pendingHeader : MerkleProofStatus.verified),
      statusChangedAt: statusChangedAt,
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'txid': txid,
      'blockHash': blockHash,
      'blockHeight': blockHeight,
      'position': position,
      'merkleProofJson': merkleProofJson,
      'createdAt': createdAt.toIso8601String(),
      'status': status,
      'statusChangedAt': statusChangedAt?.toIso8601String(),
    };
  }

  /// Deserialize from JSON for restore
  factory MerkleProofEntity.fromJson(Map<String, dynamic> json) {
    final changedAt = json['statusChangedAt'] as String?;
    return MerkleProofEntity()
      ..txid = json['txid'] as String
      ..blockHash = json['blockHash'] as String?
      ..blockHeight = json['blockHeight'] as int
      ..position = json['position'] as int
      ..merkleProofJson = json['merkleProofJson'] as String
      ..createdAt = DateTime.parse(json['createdAt'] as String)
      ..status = json['status'] as String?
      ..statusChangedAt = changedAt == null ? null : DateTime.parse(changedAt);
  }
}

