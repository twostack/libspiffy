/// UTXO Creation Integration Tests via SPV Flow
/// 
/// These tests validate that BitcoinUtxoEntity is correctly created/updated
/// in Isar database when payments are processed through the SPV flow.
/// 
/// Test Cases:
/// 1. Receiver gets BitcoinUtxoEntity created after SPV validation
/// 2. Sender gets BitcoinUtxoEntity marked as spent after sending
/// 3. Sender gets change BitcoinUtxoEntity created after sending
///
/// Uses real testnet transaction data with valid merkle proofs.

import 'dart:async';
import 'dart:io';
import 'dart:typed_data';
import 'package:test/test.dart';
import 'package:dactor/dactor.dart';
import 'package:isar/isar.dart';
