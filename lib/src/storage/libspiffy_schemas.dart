        heldInputs: DeferredPayment.heldInputsFromJson(heldInputsJson),
        state: DeferredPayment.stateFromName(state),
        lastNetworkStatus: lastNetworkStatus,
        lastNetworkStatusSource: lastNetworkStatusSource,
        lastCheckedAt: lastCheckedAt,
        createdAt: createdAt,
        updatedAt: updatedAt,
        resolvedAt: resolvedAt,
        resolutionReason: resolutionReason,
        inferred: inferred,
        competingTxids: List<String>.from(competingTxids),
      );
}

/// Bitcoin UTXO storage entity
@collection
class BitcoinUtxoEntity {
  Id id = Isar.autoIncrement;

  /// Wallet ID this UTXO belongs to
  ///
  /// The composite (walletId, status) index lets the UTXO queries select a
  /// wallet's unspent or available rows without reading its spent ones
  /// (audit S-16). The composite (walletId, txid) index does the same for
  /// one transaction's outputs: the plain `txid` index below covers every
  /// wallet that holds an output of that transaction, so a lookup through it
  /// reads another wallet's rows (bead libspiffy-36jt).
  @Index()
  @Index(composite: [CompositeIndex('status')])
  @Index(composite: [CompositeIndex('txid')])
  late String walletId;

  /// Transaction ID
  @Index()
  late String txid;

  /// Output index
  late int vout;

  /// UTXO key (txid:vout)
  ///
  /// Unique per wallet, not globally (audit 2026-09-14 S-05): two wallets
  /// in one store can hold the same outpoint. Relaxing the former global
  /// unique index cannot fail on existing data when Isar rebuilds it.
  @Index(unique: true, composite: [CompositeIndex('walletId')])
  late String utxoKey;

  /// Value in satoshis (as string to handle BigInt)
  late String satoshis;

  /// Script public key (hex)
  late String scriptPubKey;

  /// Address (if derivable)
  String? address;

  /// Block height where this UTXO was created
  int? blockHeight;

  /// Number of confirmations
  late int confirmations;

  /// UTXO status ('available', 'reserved', 'spent')
  @Index()
  late String status;

  /// When this UTXO was created
  late DateTime createdAt;

  /// When this UTXO was last updated ([BitcoinUtxo.updatedAt]); null on
  /// rows written before it was stored (read back as [createdAt]).
  DateTime? updatedAt;

  /// When this UTXO was first stored as spent (if applicable). Part of the
  /// spend history: set once, never overwritten or cleared by an update.
  DateTime? spentAt;

  /// Transaction ID that spent this UTXO (if applicable)
  String? spentInTxId;

  /// Script type ('p2pkh', 'p2sh', 'multisig', etc.)
  late String scriptType;

  /// Whether the row's [status] is `available` — exactly
  /// [BitcoinUtxo.isAvailable], and nothing more.
  ///
  /// **Not `WalletBalances.isSpendable`**, which this was called until bead
  /// libspiffy-p8qc. That rule takes the whole wallet state — the watch
  /// addresses, the wallet's own addresses (for an output it cannot unlock
  /// alone), the deferred holds — so a per-row boolean cannot hold it and
  /// cannot stay correct: registering one watch address or deriving one key
  /// changes the answer for rows already written, and nothing rewrites
  /// them. The read side answers that question live, over the state it
  /// depends on (`splitBalanceUtxos`). The name promised the rule and
  /// stored the status, so the first query to filter on it would have
  /// selected plugin-managed, watch-only and cannot-unlock-alone outputs.
  late bool isAvailable;

  /// UTXO category ('funding', 'special', 'protocol')
  late String category;

  /// Plugin metadata as JSON string (null for standard P2PKH UTXOs)
  String? pluginMetadataJson;

  /// [BitcoinUtxo.derivationIndex]; null on rows written before it was
  /// stored.
  int? derivationIndex;

  /// The reservation of a reserved UTXO ([BitcoinUtxo.reservedByTxId],
  /// [BitcoinUtxo.reservationReason], [BitcoinUtxo.reservationExpiresAt],
  /// [BitcoinUtxo.reservationPriority]) and the status its release restores
  /// ([BitcoinUtxo.statusBeforeReservation], a [UTXOStatus] name). Null when
  /// not reserved, and on rows written before they were stored (bead
  /// libspiffy-viy).
  String? reservedByTxId;
  String? reservationReason;
  DateTime? reservationExpiresAt;
  int? reservationPriority;
  String? statusBeforeReservation;

  BitcoinUtxoEntity();

  /// Create from domain model BitcoinUtxo
  ///
  /// [walletId] is empty unless given; the storage sets it.
  factory BitcoinUtxoEntity.fromDomain(BitcoinUtxo utxo, {String walletId = ''}) {
    return BitcoinUtxoEntity()
      ..walletId = walletId
      ..txid = utxo.txid
      ..vout = utxo.vout
      ..utxoKey = '${utxo.txid}:${utxo.vout}'
      ..createdAt = utxo.createdAt
      ..scriptType = 'p2pkh' // Default, could be enhanced
      ..category = 'funding' // Default category
      ..applyDomain(utxo);
  }

  /// Copies the mutable state of [utxo] onto this row (the insert and the
  /// update path of the storage share it). A block height, plugin metadata
  /// or derivation index [utxo] lacks keeps the stored value; the spend
  /// history ([spentAt], [spentInTxId]) is only ever added to. The
  /// reservation fields follow [utxo] (a release clears them).
  void applyDomain(BitcoinUtxo utxo) {
    satoshis = utxo.satoshis.toString();
    scriptPubKey = utxo.scriptPubKey;
    address = utxo.address;
    // A zero-confirmation update (reorg, audit 3b0) clears the height.
    blockHeight = utxo.blockHeight ?? ((utxo.confirmations ?? 0) > 0 ? blockHeight : null);
    confirmations = utxo.confirmations ?? 0;
    status = utxo.status.name;
    updatedAt = utxo.updatedAt;
    if (utxo.status == UTXOStatus.spent) spentAt ??= utxo.updatedAt;
    isAvailable = utxo.status == UTXOStatus.available;
    if (utxo.pluginMetadata != null) {
      pluginMetadataJson = jsonEncode(utxo.pluginMetadata);
    }
    spentInTxId ??= utxo.spentInTxId;
    derivationIndex = utxo.derivationIndex ?? derivationIndex;
    reservedByTxId = utxo.reservedByTxId;
    reservationReason = utxo.reservationReason;
    reservationExpiresAt = utxo.reservationExpiresAt;
    reservationPriority = utxo.reservationPriority;
    statusBeforeReservation = utxo.statusBeforeReservation?.name;
  }

  /// Convert back to domain model BitcoinUtxo
  BitcoinUtxo toDomain() {
    // Parse status from stored string
    final utxoStatus = UTXOStatus.values.firstWhere(
      (s) => s.name == status,
      orElse: () => UTXOStatus.pending,  // Default fallback
    );
    
    // The stored timestamps, not "now" (audit S-20).
    return BitcoinUtxo(
      txid: txid,
      vout: vout,
      value: dartsv.Coin.ofSat(BigInt.parse(satoshis)),
      scriptPubKey: scriptPubKey,
      address: address ?? '',
      blockHeight: blockHeight,
      confirmations: confirmations,
      status: utxoStatus,
      createdAt: createdAt,
      updatedAt: updatedAt ?? createdAt,
      pluginMetadata: pluginMetadataJson != null
          ? Map<String, dynamic>.from(jsonDecode(pluginMetadataJson!) as Map)
          : null,
      derivationIndex: derivationIndex,
      reservedByTxId: reservedByTxId,
      reservationReason: reservationReason,
      reservationExpiresAt: reservationExpiresAt,
      reservationPriority: reservationPriority,
      statusBeforeReservation: UTXOStatus.values
          .where((s) => s.name == statusBeforeReservation)
          .firstOrNull,
      spentInTxId: spentInTxId,
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'walletId': walletId,
      'txid': txid,
      'vout': vout,
      'utxoKey': utxoKey,
      'satoshis': satoshis,
      'scriptPubKey': scriptPubKey,
      'address': address,
      'blockHeight': blockHeight,
      'confirmations': confirmations,
      'status': status,
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      'spentAt': spentAt?.toIso8601String(),
      'spentInTxId': spentInTxId,
      'scriptType': scriptType,
      'isAvailable': isAvailable,
      'category': category,
      'pluginMetadataJson': pluginMetadataJson,
      'derivationIndex': derivationIndex,
      'reservedByTxId': reservedByTxId,
      'reservationReason': reservationReason,
      'reservationExpiresAt': reservationExpiresAt?.toIso8601String(),
      'reservationPriority': reservationPriority,
      'statusBeforeReservation': statusBeforeReservation,
    };
  }

  /// Deserialize from JSON for restore
  factory BitcoinUtxoEntity.fromJson(Map<String, dynamic> json) {
    return BitcoinUtxoEntity()
      ..walletId = json['walletId'] as String
      ..txid = json['txid'] as String
      ..vout = json['vout'] as int
      ..utxoKey = json['utxoKey'] as String
      ..satoshis = json['satoshis'] as String
      ..scriptPubKey = json['scriptPubKey'] as String
      ..address = json['address'] as String?
      ..blockHeight = json['blockHeight'] as int?
      ..confirmations = json['confirmations'] as int
      ..status = json['status'] as String
      ..createdAt = DateTime.parse(json['createdAt'] as String)
      ..updatedAt = json['updatedAt'] != null ? DateTime.parse(json['updatedAt'] as String) : null
      ..spentAt = json['spentAt'] != null ? DateTime.parse(json['spentAt'] as String) : null
      ..spentInTxId = json['spentInTxId'] as String?
      ..scriptType = json['scriptType'] as String
      // Backups written before bead libspiffy-p8qc carry the old key.
      ..isAvailable = (json['isAvailable'] ?? json['isSpendable']) as bool
      ..category = json['category'] as String
      ..pluginMetadataJson = json['pluginMetadataJson'] as String?
      ..derivationIndex = json['derivationIndex'] as int?
      ..reservedByTxId = json['reservedByTxId'] as String?
      ..reservationReason = json['reservationReason'] as String?
      ..reservationExpiresAt = json['reservationExpiresAt'] != null
          ? DateTime.parse(json['reservationExpiresAt'] as String)
          : null
      ..reservationPriority = json['reservationPriority'] as int?
      ..statusBeforeReservation = json['statusBeforeReservation'] as String?;
  }
}

/// Bitcoin transaction storage entity
@collection
class BitcoinTransactionEntity {
  Id id = Isar.autoIncrement;

  /// Wallet ID this transaction belongs to
  ///
  /// The composite (walletId, createdAt) index serves the newest-first,
  /// paginated history query (audit S-16).
  @Index()
  @Index(composite: [CompositeIndex('createdAt')])
  late String walletId;

  /// Transaction ID
  ///
  /// Unique per wallet (audit 2026-09-14 S-05): when wallet A pays wallet B
  /// in the same store each wallet has its own row. The plain `txid` index
  /// serves wallet-independent lookups.
  @Index()
  @Index(unique: true, composite: [CompositeIndex('walletId')])
  late String txid;

  /// Raw transaction hex
  late String rawHex;

  /// Block height (null if unconfirmed)
  int? blockHeight;

  /// Block hash (null if unconfirmed)
  String? blockHash;

  /// Number of confirmations
  late int confirmations;

  /// Total input amount (as string to handle BigInt)
  late String totalInput;

  /// Total output amount (as string to handle BigInt)
  late String totalOutput;

  /// Transaction fee (as string to handle BigInt)
  late String fee;
  
  /// Net amount from wallet's perspective (as string to handle BigInt)
  /// Positive for incoming, negative for outgoing
  late String netAmount;

  /// Whether this is an incoming transaction
  late bool isIncoming;

  /// Whether this is an outgoing transaction
  late bool isOutgoing;

  /// Transaction status ('pending', 'confirmed', 'failed')
  ///
  /// The composite (status, walletId) index serves status queries across
  /// every wallet (prefix) and for one wallet, so a wallet's query does not
  /// read other wallets' rows (audit S-16). The composite (status,
  /// blockHeight) index serves the confirmed rows at or above a height (a
  /// header-chain reorganization) without reading the confirmed history
  /// (bead libspiffy-ctkm). The composite (status, updatedAt) index serves a
  /// bounded window of the rows with a status that changed recently (bead
  /// libspiffy-5bju: ARCActor polling recently failed transactions) without
  /// reading that status's whole history.
  @Index(composite: [CompositeIndex('walletId')])
  @Index(composite: [CompositeIndex('blockHeight')])
  @Index(composite: [CompositeIndex('updatedAt')])
  late String status;

  /// When this transaction was created/received
  @Index()
  late DateTime createdAt;

  /// When this row was last updated ([BitcoinTransaction.updatedAt]); null
  /// on rows written before it was stored (read back as [createdAt]).
  DateTime? updatedAt;

  /// When this transaction was confirmed (if applicable)
  DateTime? confirmedAt;

  /// When this transaction was broadcast
  DateTime? broadcastAt;

  /// Counterparty information (who sent/received)
  String? counterparty;

  /// Notes or metadata about this transaction
  String? notes;

  /// Receiving addresses (stored as JSON array string)
  late String receivingAddressesJson = '[]';

  /// Sending addresses (stored as JSON array string)
  late String sendingAddressesJson = '[]';

  /// Primary counterparty for quick filtering
  @Index()
  String? primaryCounterparty;

  /// The app's opaque marker for the counterparty this payment was with
  /// (bead libspiffy-cq16, spv-understanding.md "Core Data Management"
  /// requirement 5). Distinct from [counterparty] and
  /// [primaryCounterparty], which are derived from bitcoin ADDRESSES (v015):
  /// an address is not an identity. Set once, by the first record that
  /// carries one, and never blanked or replaced
  /// ([TransactionRowRules.counterpartyMarkerAfter]). Null on rows written
  /// before the field existed.
  String? counterpartyMarker;

  /// The transaction's `nLockTime` (bead libspiffy-zpu7). Null on rows
  /// written before the field existed; [toDomain] recovers those from
  /// [rawHex] where it is a transaction we can read, and leaves them null
  /// where it is not — a `0` here would say "spendable now" about a refund
  /// that is locked.
  int? lockTime;

  /// The transaction's version field (bead libspiffy-zpu7). Null on rows
  /// written before the field existed, recovered from [rawHex] on read as
  /// [lockTime] is.
  int? version;

  BitcoinTransactionEntity();

  /// Create from domain model BitcoinTransaction
  ///
  /// The single conversion used by the storage for a new row (audit S-21).
  /// [walletId] overrides [BitcoinTransaction.walletId] (empty when neither
  /// is given).
  factory BitcoinTransactionEntity.fromDomain(BitcoinTransaction tx, {String? walletId}) {
    return BitcoinTransactionEntity()
      ..walletId = walletId ?? tx.walletId ?? ''
      ..txid = tx.txid
      ..rawHex = tx.rawHex
      ..blockHash = null // Not available in BitcoinTransaction
      ..createdAt = tx.createdAt
      ..broadcastAt = null // Not available in BitcoinTransaction
      ..counterparty = primaryCounterpartyOf(tx)
      ..applyDomain(tx);
  }

  /// Copies the mutable state of [tx] onto this row (the insert and the
  /// update path of the storage share it). History is not erased: an empty
  /// raw hex or a null block height keeps the stored value (an SPV wallet
  /// cannot fetch the transaction again), `confirmedAt` is set once the
  /// transaction has a block height and is not cleared, and the counterparty
  /// marker is set once and never blanked or replaced (cq16).
  void applyDomain(BitcoinTransaction tx) {
    final net = tx.netAmount;
    if (tx.rawHex.isNotEmpty) rawHex = tx.rawHex;
    status = tx.status.name;
    // A non-confirmed update clears the height (reorg, audit 3b0).
    blockHeight = tx.blockHeight ?? (tx.status == TransactionStatus.confirmed ? blockHeight : null);
    confirmations = tx.confirmations ?? 0;
    totalInput = tx.inputValue.toString();
    totalOutput = tx.outputValue.toString();
    fee = tx.fee.toString();
    netAmount = net.toString();
    isIncoming = net > BigInt.zero;
    isOutgoing = net < BigInt.zero;
    receivingAddressesJson = jsonEncode(tx.receivingAddresses);
    sendingAddressesJson = jsonEncode(tx.sendingAddresses);
    primaryCounterparty = primaryCounterpartyOf(tx);
    // Set once, never blanked, never replaced (cq16).
    counterpartyMarker = TransactionRowRules.counterpartyMarkerAfter(counterpartyMarker, tx.counterpartyMarker);
    notes = tx.memo;
    // Consensus fields the txid commits to: set once, never blanked and
    // never revised by a later record (zpu7).
    final intrinsics = TransactionRowRules.intrinsicsOf(tx);
    lockTime = TransactionRowRules.intrinsicAfter(lockTime, intrinsics.lockTime);
    version = TransactionRowRules.intrinsicAfter(version, intrinsics.version);
    updatedAt = tx.updatedAt;
    if (tx.blockHeight != null && tx.blockHeight! > 0) {
      confirmedAt = tx.updatedAt;
    }
  }

  /// The other party of [tx] from the wallet's perspective: the first
  /// sending address of an incoming transaction, the first receiving
  /// address of an outgoing one, null otherwise.
  /// The rule every backend shares ([TransactionRowRules.primaryCounterpartyOf]).
  static String? primaryCounterpartyOf(BitcoinTransaction tx) => TransactionRowRules.primaryCounterpartyOf(tx);

  /// Convert back to domain model BitcoinTransaction
  BitcoinTransaction toDomain() {
    final receiving = receivingAddressesJson.isNotEmpty && receivingAddressesJson != '[]'
        ? (jsonDecode(receivingAddressesJson) as List).cast<String>()
        : <String>[];
    final sending = sendingAddressesJson.isNotEmpty && sendingAddressesJson != '[]'
        ? (jsonDecode(sendingAddressesJson) as List).cast<String>()
        : <String>[];
    final recovered = (lockTime == null || version == null)
        ? TransactionRowRules.intrinsicsOfRawHex(rawHex)
        : null;

    return BitcoinTransaction(
      walletId: walletId.isNotEmpty ? walletId : null,
      txid: txid,
      rawHex: rawHex,
      status: TransactionStatus.values.firstWhere((s) => s.name == status),
      blockHeight: blockHeight,
      confirmations: confirmations,
      inputValue: BigInt.parse(totalInput),
      outputValue: BigInt.parse(totalOutput),
      fee: BigInt.parse(fee),
      receivingAddresses: receiving,
      sendingAddresses: sending,
      netAmount: BigInt.parse(netAmount), // Read directly from stored value
      createdAt: createdAt,
      updatedAt: updatedAt ?? createdAt,
      memo: notes,
      // Rows written before the columns existed have neither; the raw hex
      // the wallet never drops still carries both (zpu7). Where it does not,
      // the reading stays absent rather than becoming a fabricated 0/1.
      lockTime: lockTime ?? recovered?.lockTime,
      version: version ?? recovered?.version,
      counterpartyMarker: counterpartyMarker,
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'walletId': walletId,
      'txid': txid,
      'rawHex': rawHex,
      'blockHeight': blockHeight,
      'blockHash': blockHash,
      'confirmations': confirmations,
      'totalInput': totalInput,
      'totalOutput': totalOutput,
      'fee': fee,
      'netAmount': netAmount,
      'isIncoming': isIncoming,
      'isOutgoing': isOutgoing,
      'status': status,
      'createdAt': createdAt.toIso8601String(),
      'updatedAt': updatedAt?.toIso8601String(),
      'confirmedAt': confirmedAt?.toIso8601String(),
      'broadcastAt': broadcastAt?.toIso8601String(),
      'counterparty': counterparty,
      'notes': notes,
      'receivingAddressesJson': receivingAddressesJson,
      'sendingAddressesJson': sendingAddressesJson,
      'primaryCounterparty': primaryCounterparty,
      'counterpartyMarker': counterpartyMarker,
      'lockTime': lockTime,
      'version': version,
    };
  }

  /// Deserialize from JSON for restore
  factory BitcoinTransactionEntity.fromJson(Map<String, dynamic> json) {
    return BitcoinTransactionEntity()
      ..walletId = json['walletId'] as String
      ..txid = json['txid'] as String
      ..rawHex = json['rawHex'] as String
      ..blockHeight = json['blockHeight'] as int?
      ..blockHash = json['blockHash'] as String?
      ..confirmations = json['confirmations'] as int
      ..totalInput = json['totalInput'] as String
      ..totalOutput = json['totalOutput'] as String
      ..fee = json['fee'] as String
      ..netAmount = json['netAmount'] as String
      ..isIncoming = json['isIncoming'] as bool
      ..isOutgoing = json['isOutgoing'] as bool
      ..status = json['status'] as String
      ..createdAt = DateTime.parse(json['createdAt'] as String)
      ..updatedAt = json['updatedAt'] != null ? DateTime.parse(json['updatedAt'] as String) : null
      ..confirmedAt = json['confirmedAt'] != null ? DateTime.parse(json['confirmedAt'] as String) : null
      ..broadcastAt = json['broadcastAt'] != null ? DateTime.parse(json['broadcastAt'] as String) : null
      ..counterparty = json['counterparty'] as String?
      ..notes = json['notes'] as String?
      ..receivingAddressesJson = json['receivingAddressesJson'] as String
      ..sendingAddressesJson = json['sendingAddressesJson'] as String
      ..primaryCounterparty = json['primaryCounterparty'] as String?
      // Absent on backups written before each field existed (cq16, zpu7).
      ..counterpartyMarker = json['counterpartyMarker'] as String?
      ..lockTime = json['lockTime'] as int?
      ..version = json['version'] as int?;
  }
}

