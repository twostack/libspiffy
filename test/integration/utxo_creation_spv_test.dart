/// Verify that an address exists in the database for the given wallet
Future<void> _verifyAddressInDatabase({
  required Isar isar,
  required String walletId,
  required String address,
}) async {
  // Give projection time to persist
  await Future.delayed(Duration(milliseconds: 500));
  
  final addressEntity = await isar.addressEntitys
      .filter()
      .walletIdEqualTo(walletId)
      .addressEqualTo(address)
      .findFirst();
  
  if (addressEntity != null) {
    print('✓ Address verified in database');
    print('  Address: ${addressEntity.address}');
    print('  WalletId: ${addressEntity.walletId}');
  } else {
    print('⚠️ WARNING: Address not found in database!');
    print('  Expected walletId: $walletId');
    print('  Expected address: $address');
    
    // Check if address exists under any walletId
    final anyAddress = await isar.addressEntitys
        .filter()
        .addressEqualTo(address)
        .findFirst();
    
    if (anyAddress != null) {
      print('  Found address under different walletId: ${anyAddress.walletId}');
    }
  }
  
  expect(addressEntity, isNotNull, 
    reason: 'Address $address should exist in database for wallet $walletId');
}

/// Verify UTXO exists in database with expected properties
Future<void> verifyUtxoInDatabase({
  required Isar isar,
  required String walletId,
  required String txid,
  required int vout,
  String? expectedStatus,
  Duration timeout = const Duration(seconds: 5),
}) async {
  final startTime = DateTime.now();
  BitcoinUtxoEntity? utxo;
  
  while (DateTime.now().difference(startTime) < timeout) {
    utxo = await isar.bitcoinUtxoEntitys
        .filter()
        .walletIdEqualTo(walletId)
        .txidEqualTo(txid)
        .voutEqualTo(vout)
        .findFirst();
    
    if (utxo != null) {
      if (expectedStatus == null || utxo.status == expectedStatus) {
        print('✓ UTXO verified: $txid:$vout');
        print('  Status: ${utxo.status}');
        print('  Satoshis: ${utxo.satoshis}');
        return;
      }
    }
    
    await Future.delayed(Duration(milliseconds: 100));
  }
  
  expect(utxo, isNotNull, 
    reason: 'UTXO $txid:$vout should exist for wallet $walletId');
  if (expectedStatus != null && utxo != null) {
    expect(utxo.status, equals(expectedStatus),
      reason: 'UTXO status should be $expectedStatus');
  }
}

