/// Bitcoin UTXO storage entity
@collection
class BitcoinUtxoEntity {
  Id id = Isar.autoIncrement;

  /// Wallet ID this UTXO belongs to
  @Index()
  late String walletId;

  /// Transaction ID
  @Index()
  late String txid;

  /// Output index
  late int vout;

  /// UTXO key (txid:vout)
  @Index(unique: true)
  late String utxoKey;

  /// Value in satoshis (as string to handle BigInt)
  late String satoshis;

  /// Script public key (hex)
  late String scriptPubKey;

  /// Address (if derivable)
  String? address;

  /// Block height where this UTXO was created
  int? blockHeight;

  /// Number of confirmations
  late int confirmations;

  /// UTXO status ('available', 'reserved', 'spent')
  @Index()
  late String status;

  /// When this UTXO was created
  late DateTime createdAt;

  /// When this UTXO was spent (if applicable)
  DateTime? spentAt;

  /// Transaction ID that spent this UTXO (if applicable)
  String? spentInTxId;

  /// Script type ('p2pkh', 'p2sh', 'multisig', etc.)
  late String scriptType;

  /// Whether this UTXO is spendable by the wallet
  late bool isSpendable;

  /// UTXO category ('funding', 'special', 'protocol')
  late String category;

  /// Plugin metadata as JSON string (null for standard P2PKH UTXOs)
  String? pluginMetadataJson;

  BitcoinUtxoEntity();

  /// Create from domain model BitcoinUtxo
  factory BitcoinUtxoEntity.fromDomain(BitcoinUtxo utxo) {
    return BitcoinUtxoEntity()
      ..walletId = '' // Will be set by the storage implementation
      ..txid = utxo.txid
      ..vout = utxo.vout
      ..utxoKey = '${utxo.txid}:${utxo.vout}'
      ..satoshis = utxo.satoshis.toString()
      ..scriptPubKey = utxo.scriptPubKey
      ..address = utxo.address
      ..blockHeight = utxo.blockHeight
      ..confirmations = utxo.confirmations ?? 0
      ..status = utxo.status.name
      ..createdAt = utxo.createdAt
      ..spentAt = utxo.status == UTXOStatus.spent ? utxo.updatedAt : null
      ..spentInTxId = null // This info would come from spending transaction
      ..scriptType = 'p2pkh' // Default, could be enhanced
      ..isSpendable = utxo.status == UTXOStatus.available
      ..category = 'funding' // Default category
      ..pluginMetadataJson = utxo.pluginMetadata != null
          ? jsonEncode(utxo.pluginMetadata)
          : null;
  }

  /// Convert back to domain model BitcoinUtxo
  BitcoinUtxo toDomain() {
    // Parse status from stored string
    final utxoStatus = UTXOStatus.values.firstWhere(
      (s) => s.name == status,
      orElse: () => UTXOStatus.pending,  // Default fallback
    );
    
    return BitcoinUtxo.create(
      txid: txid,
      vout: vout,
      satoshis: BigInt.parse(satoshis),
      scriptPubKey: scriptPubKey,
      address: address ?? '',
      blockHeight: blockHeight,
      confirmations: confirmations,
      status: utxoStatus,
      pluginMetadata: pluginMetadataJson != null
          ? Map<String, dynamic>.from(jsonDecode(pluginMetadataJson!) as Map)
          : null,
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'walletId': walletId,
      'txid': txid,
      'vout': vout,
      'utxoKey': utxoKey,
      'satoshis': satoshis,
      'scriptPubKey': scriptPubKey,
      'address': address,
      'blockHeight': blockHeight,
      'confirmations': confirmations,
      'status': status,
      'createdAt': createdAt.toIso8601String(),
      'spentAt': spentAt?.toIso8601String(),
      'spentInTxId': spentInTxId,
      'scriptType': scriptType,
      'isSpendable': isSpendable,
      'category': category,
      'pluginMetadataJson': pluginMetadataJson,
    };
  }

  /// Deserialize from JSON for restore
  factory BitcoinUtxoEntity.fromJson(Map<String, dynamic> json) {
    return BitcoinUtxoEntity()
      ..walletId = json['walletId'] as String
      ..txid = json['txid'] as String
      ..vout = json['vout'] as int
      ..utxoKey = json['utxoKey'] as String
      ..satoshis = json['satoshis'] as String
      ..scriptPubKey = json['scriptPubKey'] as String
      ..address = json['address'] as String?
      ..blockHeight = json['blockHeight'] as int?
      ..confirmations = json['confirmations'] as int
      ..status = json['status'] as String
      ..createdAt = DateTime.parse(json['createdAt'] as String)
      ..spentAt = json['spentAt'] != null ? DateTime.parse(json['spentAt'] as String) : null
      ..spentInTxId = json['spentInTxId'] as String?
      ..scriptType = json['scriptType'] as String
      ..isSpendable = json['isSpendable'] as bool
      ..category = json['category'] as String
      ..pluginMetadataJson = json['pluginMetadataJson'] as String?;
  }
}

/// Bitcoin transaction storage entity
@collection
class BitcoinTransactionEntity {
  Id id = Isar.autoIncrement;

  /// Wallet ID this transaction belongs to
  @Index()
  late String walletId;

  /// Transaction ID
  @Index(unique: true)
  late String txid;

  /// Raw transaction hex
  late String rawHex;

  /// Block height (null if unconfirmed)
  int? blockHeight;

  /// Block hash (null if unconfirmed)
  String? blockHash;

  /// Number of confirmations
  late int confirmations;

  /// Total input amount (as string to handle BigInt)
  late String totalInput;

  /// Total output amount (as string to handle BigInt)
  late String totalOutput;

  /// Transaction fee (as string to handle BigInt)
  late String fee;
  
  /// Net amount from wallet's perspective (as string to handle BigInt)
  /// Positive for incoming, negative for outgoing
  late String netAmount;

  /// Whether this is an incoming transaction
  late bool isIncoming;

  /// Whether this is an outgoing transaction
  late bool isOutgoing;

  /// Transaction status ('pending', 'confirmed', 'failed')
  @Index()
  late String status;

  /// When this transaction was created/received
  @Index()
  late DateTime createdAt;

  /// When this transaction was confirmed (if applicable)
  DateTime? confirmedAt;

  /// When this transaction was broadcast
  DateTime? broadcastAt;

  /// Counterparty information (who sent/received)
  String? counterparty;

  /// Notes or metadata about this transaction
  String? notes;

  /// Receiving addresses (stored as JSON array string)
  late String receivingAddressesJson = '[]';

  /// Sending addresses (stored as JSON array string)
  late String sendingAddressesJson = '[]';

  /// Primary counterparty for quick filtering
  @Index()
  String? primaryCounterparty;

  BitcoinTransactionEntity();

  /// Create from domain model BitcoinTransaction
  factory BitcoinTransactionEntity.fromDomain(BitcoinTransaction tx) {
    // Calculate net amount (positive for incoming, negative for outgoing)
    final netAmount = tx.netAmount;
    
    return BitcoinTransactionEntity()
      ..walletId = tx.walletId ?? '' // Use transaction's walletId or empty string as fallback
      ..txid = tx.txid
      ..rawHex = tx.rawHex
      ..blockHeight = tx.blockHeight
      ..blockHash = tx.blockHeight != null ? '' : null // Would need actual hash
      ..confirmations = tx.confirmations ?? 0
      ..totalInput = tx.inputValue.toString()
      ..totalOutput = tx.outputValue.toString()
      ..fee = tx.fee.toString()
      ..netAmount = netAmount.toString()
      ..isIncoming = netAmount > BigInt.zero
      ..isOutgoing = netAmount < BigInt.zero
      ..status = tx.status.name
      ..createdAt = tx.createdAt
      ..confirmedAt = null // Not directly available in model
      ..broadcastAt = null // Not directly available in model
      ..receivingAddressesJson = jsonEncode(tx.receivingAddresses)
      ..sendingAddressesJson = jsonEncode(tx.sendingAddresses)
      ..primaryCounterparty = _getPrimaryCounterparty(tx, netAmount)
      ..counterparty = null
      ..notes = tx.memo;
  }

  static String? _getPrimaryCounterparty(BitcoinTransaction tx, BigInt netAmount) {
    if (netAmount > BigInt.zero) {
      return tx.sendingAddresses.isNotEmpty ? tx.sendingAddresses.first : null;
    } else if (netAmount < BigInt.zero) {
      return tx.receivingAddresses.isNotEmpty ? tx.receivingAddresses.first : null;
    }
    return null;
  }

  /// Convert back to domain model BitcoinTransaction
  BitcoinTransaction toDomain() {
    final receiving = receivingAddressesJson.isNotEmpty && receivingAddressesJson != '[]'
        ? (jsonDecode(receivingAddressesJson) as List).cast<String>()
        : <String>[];
    final sending = sendingAddressesJson.isNotEmpty && sendingAddressesJson != '[]'
        ? (jsonDecode(sendingAddressesJson) as List).cast<String>()
        : <String>[];
    
    return BitcoinTransaction(
      walletId: walletId.isNotEmpty ? walletId : null,
      txid: txid,
      rawHex: rawHex,
      status: TransactionStatus.values.firstWhere((s) => s.name == status),
      blockHeight: blockHeight,
      confirmations: confirmations,
      inputValue: BigInt.parse(totalInput),
      outputValue: BigInt.parse(totalOutput),
      fee: BigInt.parse(fee),
      receivingAddresses: receiving,
      sendingAddresses: sending,
      netAmount: BigInt.parse(netAmount), // Read directly from stored value
      createdAt: createdAt,
      updatedAt: createdAt, // Use createdAt as fallback
      memo: notes,
      lockTime: 0, // Would need to parse from rawHex or store separately
      version: 1, // Would need to parse from rawHex or store separately
    );
  }

  /// Serialize to JSON for backup
  Map<String, dynamic> toJson() {
    return {
      'walletId': walletId,
      'txid': txid,
      'rawHex': rawHex,
      'blockHeight': blockHeight,
      'blockHash': blockHash,
      'confirmations': confirmations,
      'totalInput': totalInput,
      'totalOutput': totalOutput,
      'fee': fee,
      'netAmount': netAmount,
      'isIncoming': isIncoming,
      'isOutgoing': isOutgoing,
      'status': status,
      'createdAt': createdAt.toIso8601String(),
      'confirmedAt': confirmedAt?.toIso8601String(),
      'broadcastAt': broadcastAt?.toIso8601String(),
      'counterparty': counterparty,
      'notes': notes,
      'receivingAddressesJson': receivingAddressesJson,
      'sendingAddressesJson': sendingAddressesJson,
      'primaryCounterparty': primaryCounterparty,
    };
  }

  /// Deserialize from JSON for restore
  factory BitcoinTransactionEntity.fromJson(Map<String, dynamic> json) {
    return BitcoinTransactionEntity()
      ..walletId = json['walletId'] as String
      ..txid = json['txid'] as String
      ..rawHex = json['rawHex'] as String
      ..blockHeight = json['blockHeight'] as int?
      ..blockHash = json['blockHash'] as String?
      ..confirmations = json['confirmations'] as int
      ..totalInput = json['totalInput'] as String
      ..totalOutput = json['totalOutput'] as String
      ..fee = json['fee'] as String
      ..netAmount = json['netAmount'] as String
      ..isIncoming = json['isIncoming'] as bool
      ..isOutgoing = json['isOutgoing'] as bool
      ..status = json['status'] as String
      ..createdAt = DateTime.parse(json['createdAt'] as String)
      ..confirmedAt = json['confirmedAt'] != null ? DateTime.parse(json['confirmedAt'] as String) : null
      ..broadcastAt = json['broadcastAt'] != null ? DateTime.parse(json['broadcastAt'] as String) : null
      ..counterparty = json['counterparty'] as String?
      ..notes = json['notes'] as String?
      ..receivingAddressesJson = json['receivingAddressesJson'] as String
      ..sendingAddressesJson = json['sendingAddressesJson'] as String
      ..primaryCounterparty = json['primaryCounterparty'] as String?;
  }
}

